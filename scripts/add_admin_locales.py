for lang, keys in ADMIN_KEYS.items():
    filepath = os.path.join(LOCALES_DIR, f"{lang}.json")
    with open(filepath, encoding="utf-8") as f:
        data = json.load(f)

    new_keys = {k: v for k, v in keys.items() if k not in data}
    if new_keys:
        data.update(new_keys)
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✅ {lang}.json: added {len(new_keys)} new keys")
    else:
        print(f"ℹ️ {lang}.json: no new keys needed")
